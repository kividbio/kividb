/// Redis's settings that `CONFIG SET` takes and `CONFIG GET *` does not
/// list: debugging knobs, which Redis's own tests set (Redis 8.0's
/// `HIDDEN_CONFIG`s that can be changed, cluster ones aside), with Redis's
/// defaults.
pub const HIDDEN_SETTINGS: &[(&str, &str)] = &[
    ("aof-disable-auto-gc", "no"),
    ("key-load-delay", "0"),
    ("loading-process-events-interval-bytes", "524288"),
    ("rdb-key-save-delay", "0"),
    ("repl-rdb-channel", "yes"),
    ("use-exit-on-panic", "no"),
    ("watchdog-period", "0"),
];

/// Whether `name` is one of [`HIDDEN_SETTINGS`].
pub fn is_hidden(name: &str) -> bool {
    HIDDEN_SETTINGS.iter().any(|(hidden, _)| *hidden == name)
}

/// Whether `name` is one of Redis's settings.
pub fn is_redis_setting(name: &str) -> bool {
    REDIS_SETTINGS.binary_search(&name).is_ok() || is_hidden(name)
}

#[cfg(test)]
mod tests {
    #[test]
    fn the_list_is_sorted_for_binary_search() {
        assert!(super::REDIS_SETTINGS.windows(2).all(|w| w[0] < w[1]));
        assert!(super::is_redis_setting("maxclients"));
        assert!(super::is_redis_setting("key-load-delay"));
        assert!(!super::is_redis_setting("bogus-name"));
    }
}
