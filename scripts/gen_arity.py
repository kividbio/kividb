"""Generate src/commands/arity_table.rs from Valkey's command JSON and
KiviDB's own arities (scripts/arity_kividb.json).

usage: python -I gen_arity.py <valkey src/commands dir> <out.rs>

The base is the `arity` of every command and subcommand in Valkey's
`src/commands/*.json` (BSD-3-Clause, see NOTICE) at VALKEY_TAG /
VALKEY_COMMIT below, the same source as gen_command_docs.py and
gen_keyspecs.py. Redis 7.4 and later are not a source.

SKIP names the Valkey entries the table leaves out: commands KiviDB does
not serve, and ones whose arguments KiviDB's handler checks itself.
arity_kividb.json then adds the commands Valkey does not have, and replaces
Valkey's entry where KiviDB takes the command in another form; those lines
are marked "KiviDB's own" in the output.
"""
import json
import sys
from pathlib import Path

VALKEY_TAG = "9.1.3"
VALKEY_COMMIT = "29173b67508b2de4c0f0ed551f3b47cf19fc3ca8"

# Valkey entries left out, and why.
SKIP = {
    "CLIENT|CAPA": "not served",
    "CLIENT|IMPORT-SOURCE": "not served",
    "CLUSTERSCAN": "not served",
    "CLUSTER|CANCELSLOTMIGRATIONS": "not served",
    "CLUSTER|FLUSHSLOT": "not served",
    "CLUSTER|GETSLOTMIGRATIONS": "not served",
    "CLUSTER|MIGRATESLOTS": "not served",
    "CLUSTER|SLOT-STATS": "checked by KiviDB's handler",
    "CLUSTER|SYNCSLOTS": "KiviDB's is node-to-node, with arguments of its own",
    "COMMANDLOG": "not served",
    "COMMANDLOG|GET": "not served",
    "COMMANDLOG|HELP": "not served",
    "COMMANDLOG|LEN": "not served",
    "COMMANDLOG|RESET": "not served",
    "DELIFEQ": "not served",
    "MSETEX": "checked by KiviDB's handler",
    "SCRIPT|SHOW": "not served",
    "SENTINEL|GET-PRIMARY-ADDR-BY-NAME": "not served",
    "SENTINEL|IS-PRIMARY-DOWN-BY-ADDR": "not served",
    "SENTINEL|PRIMARIES": "not served",
    "SENTINEL|PRIMARY": "not served",
}


def valkey_arities(src: Path) -> dict[str, int]:
    out = {}
    for path in sorted(src.glob("*.json")):
        for name, cmd in json.loads(path.read_text(encoding="utf-8")).items():
            full = name.upper()
            if "container" in cmd:
                full = f"{cmd['container'].upper()}|{full}"
            out[full] = int(cmd["arity"])
    return out


def main() -> None:
    if len(sys.argv) != 3:
        print(__doc__.strip(), file=sys.stderr)
        sys.exit(2)
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    own_path = Path(__file__).with_name("arity_kividb.json")
    own = {
        name: int(entry["arity"])
        for name, entry in json.loads(own_path.read_text(encoding="utf-8")).items()
        if not name.startswith("_")
    }

    valkey = valkey_arities(src)
    stale = sorted(name for name in SKIP if name not in valkey)
    if stale:
        sys.exit(f"SKIP names entries Valkey {VALKEY_TAG} does not have: {stale}")
    table = {name: (arity, False) for name, arity in valkey.items() if name not in SKIP}
    for name, arity in own.items():
        table[name] = (arity, True)
    from_valkey = sum(1 for _, kividb in table.values() if not kividb)

    lines = [
        f"// Generated by `scripts/gen_arity.py` from the `arity` of Valkey {VALKEY_TAG}'s",
        f"// `src/commands/*.json` (commit {VALKEY_COMMIT}),",
        "// and of `scripts/arity_kividb.json`: KiviDB's own arities, marked below,",
        "// for the commands Valkey does not have or KiviDB takes in another form.",
        "// Not edited by hand.",
        "//",
        "// Valkey's files are Copyright (c) 2024-present, Valkey contributors, and",
        "// Copyright (c) 2006-2020, Redis Ltd., under the BSD 3-Clause License (see",
        "// NOTICE). This table is derived from them.",
        "",
        "/// `(command, arity)`, by command, a subcommand as `CONTAINER|SUBCOMMAND`.",
        "#[rustfmt::skip]",
        "pub(super) const TABLE: &[(&str, i16)] = &[",
    ]
    for name in sorted(table):
        arity, kividb = table[name]
        mark = " // KiviDB's own" if kividb else ""
        lines.append(f"    ({json.dumps(name)}, {arity}),{mark}")
    lines.append("];")
    with out.open("w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(len(table), "entries,", from_valkey, "from Valkey,", len(own), "KiviDB's own")


if __name__ == "__main__":
    main()
