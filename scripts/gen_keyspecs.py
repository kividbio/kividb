"""Generate src/commands/key_spec_table.rs from Valkey's src/commands/*.json
and KiviDB's own key specs (scripts/key_specs_kividb.json).

usage: python -I gen_keyspecs.py <valkey src/commands dir> <valkey version> <out.rs>

Valkey's command files are BSD-3-Clause (see NOTICE). Redis 7.4 and later
are not, so they are not a source: the commands Valkey does not have, and
the ones KiviDB implements as Redis 8 does, have specs of KiviDB's own in
key_specs_kividb.json, which replace Valkey's.
"""
import json
import sys
from pathlib import Path

src, version, out = Path(sys.argv[1]), sys.argv[2], Path(sys.argv[3])
own = Path(__file__).with_name("key_specs_kividb.json")
UPPER = {"RW", "RO", "OW", "RM"}
ORDER = ["RO", "RW", "OW", "RM", "ACCESS", "UPDATE", "INSERT", "DELETE", "NOT_KEY",
         "INCOMPLETE", "VARIABLE_FLAGS"]


def spec_lines(specs):
    lines = []
    for spec in specs:
        # In the order Redis replies with them (`addReplyFlagsForKeyArgs`).
        # Not INCOMPLETE: for such a spec Redis asks the command's own
        # getkeys function, whose keys never carry it.
        flags = " ".join(
            f if f in UPPER else f.lower()
            for f in sorted(spec.get("flags", []), key=ORDER.index)
            if f != "INCOMPLETE"
        )
        bs = spec["begin_search"]
        if "index" in bs:
            begin = f"Begin::Index({bs['index']['pos']})"
        elif "keyword" in bs:
            kw = bs["keyword"]
            begin = f"Begin::Keyword({json.dumps(kw['keyword'])}, {kw['startfrom']})"
        else:
            begin = "Begin::Unknown"
        fk = spec["find_keys"]
        if "range" in fk:
            r = fk["range"]
            find = f"Find::Range({r['lastkey']}, {r['step']}, {r['limit']})"
        elif "keynum" in fk:
            k = fk["keynum"]
            find = f"Find::KeyNum({k['keynumidx']}, {k['firstkey']}, {k['step']})"
        else:
            find = "Find::Unknown"
        lines.append(f"        Spec {{ flags: {json.dumps(flags)}, begin: {begin}, find: {find} }},")
    return lines


entries = {}
for path in sorted(src.glob("*.json")):
    doc = json.loads(path.read_text(encoding="utf-8"))
    for name, cmd in doc.items():
        specs = cmd.get("key_specs")
        if not specs:
            continue
        full = name.upper()
        if "container" in cmd:
            full = f"{cmd['container'].upper()}|{full}"
        no_keys = "NO_MANDATORY_KEYS" in cmd.get("command_flags", [])
        entries[full] = (no_keys, spec_lines(specs))
from_valkey = len(entries)

for name, cmd in json.loads(own.read_text(encoding="utf-8")).items():
    if name.startswith("_"):
        continue
    no_keys = "NO_MANDATORY_KEYS" in cmd.get("command_flags", [])
    entries[name] = (no_keys, spec_lines(cmd["key_specs"]))

body = [
    f"// Generated by `gen_keyspecs.py` from the `key_specs` of Valkey {version}'s",
    "// `src/commands/*.json`, and of `scripts/key_specs_kividb.json`: KiviDB's own",
    "// specs for the commands Valkey does not have, or has differently. Not edited",
    "// by hand.",
    "//",
    "// Valkey's files are Copyright (c) 2024-present, Valkey contributors, and",
    "// Copyright (c) 2006-2020, Redis Ltd., under the BSD 3-Clause License (see",
    "// NOTICE). This table is derived from them.",
    "",
    "use super::key_specs::{Begin, Find, Spec};",
    "",
    "/// `(command, whether it may have no keys, its key specs)`, by command.",
    "#[rustfmt::skip]",
    "pub(super) const TABLE: &[(&str, bool, &[Spec])] = &[",
]
for name in sorted(entries):
    no_keys, lines = entries[name]
    body.append(f"    ({json.dumps(name)}, {'true' if no_keys else 'false'}, &[")
    body.extend(lines)
    body.append("    ]),")
body.append("];")
out.write_text("\n".join(body) + "\n", encoding="utf-8")
print(len(entries), "commands,", from_valkey, "from Valkey")
